#!/usr/bin/env python3
"""Conflict-level bootstrap 95% CI for Whole-File Exact Match.

The evaluation set has 185 files generated by 135 merge conflicts. Files from
the same conflict share parents and surrounding code, so confidence intervals
should resample conflict IDs rather than treating files as independent units.
The point estimate remains file-level EM; each bootstrap replicate samples 135
conflicts with replacement and includes all evaluated files from sampled
conflicts.

Also runs McNemar tests for all pairs of the top-5 models by EM.
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import chi2

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
RESULTS_DIR = Path("data/predictions")
DATASETS = ["lite", "Verified", "Multilingual", "Multimodal"]

# ---------------------------------------------------------------------------
# 1. Load data
# ---------------------------------------------------------------------------
records = []
for ds in DATASETS:
    path = RESULTS_DIR / f"{ds}_whole_file.jsonl"
    with open(path) as fh:
        for line in fh:
            row = json.loads(line)
            records.append(row)

print(f"Loaded {len(records)} records across {len(DATASETS)} datasets.", flush=True)

# ---------------------------------------------------------------------------
# 2. Aggregate per model: hits grouped by conflict ID
# ---------------------------------------------------------------------------
model_hits_by_conflict: dict[str, dict[str, list[int]]] = defaultdict(lambda: defaultdict(list))
for r in records:
    model_hits_by_conflict[r["model_name"]][r["conflict_id"]].append(
        1 if r["exact_match"] else 0
    )

# ---------------------------------------------------------------------------
# 3. Bootstrap 95% CI (10 000 resamples, seed=42)
# ---------------------------------------------------------------------------
RNG = np.random.default_rng(42)
N_BOOT = 10_000


def bootstrap_conflict_mean_ci(grouped_hits, n_boot=N_BOOT, rng=RNG):
    """Return (mean, lower_95, upper_95) using conflict-level resampling."""
    conflicts = np.asarray(sorted(grouped_hits), dtype=object)
    flat = np.asarray([hit for cid in conflicts for hit in grouped_hits[cid]], dtype=float)
    obs_mean = flat.mean()
    boot_means = np.empty(n_boot, dtype=float)
    for i in range(n_boot):
        sampled = rng.choice(conflicts, size=len(conflicts), replace=True)
        hits = [hit for cid in sampled for hit in grouped_hits[cid]]
        boot_means[i] = np.mean(hits)
    lo = float(np.percentile(boot_means, 2.5))
    hi = float(np.percentile(boot_means, 97.5))
    return obs_mean, lo, hi


results = {}
for model, grouped_hits in model_hits_by_conflict.items():
    hits = [hit for group in grouped_hits.values() for hit in group]
    mean, lo, hi = bootstrap_conflict_mean_ci(grouped_hits)
    results[model] = {
        "em": mean * 100,
        "ci_lo": lo * 100,
        "ci_hi": hi * 100,
        "n": len(hits),
        "n_conflicts": len(grouped_hits),
        "hits": hits,  # keep for McNemar
    }

# Sort by EM descending
sorted_models = sorted(results.items(), key=lambda x: -x[1]["em"])

# ---------------------------------------------------------------------------
# 4. Print LaTeX table rows (all models, sorted by EM desc)
# ---------------------------------------------------------------------------
print("\n% ---- LaTeX tabular rows (EM desc) ----")
print(r"\begin{tabular}{rlrrr}")
print(r"\toprule")
print(r"Rk & Model & EM\,(\%) & 95\,\% CI & $N$ \\")
print(r"\midrule")
for rank, (model, d) in enumerate(sorted_models, 1):
    em = d["em"]
    lo = d["ci_lo"]
    hi = d["ci_hi"]
    n = d["n"]
    ci_str = f"[{lo:.1f}, {hi:.1f}]"
    print(f"{rank} & {model} & {em:.1f} & {ci_str} & {n} \\\\")
print(r"\bottomrule")
print(r"\end{tabular}")

# ---------------------------------------------------------------------------
# 5. McNemar test for all pairs of top-5 models
# ---------------------------------------------------------------------------
top5 = sorted_models[:5]

print("\n% ---- McNemar p-values for top-5 model pairs ----")
print(f"{'Model A':<35} {'Model B':<35} {'b':>5} {'c':>5} {'p-value':>12} {'sig?':>6}")
print("-" * 100)

# Build conflict-id -> em mapping per model for paired comparison
# Since data spans multiple datasets, we pair by (conflict_id, file_path) key
model_em_map: dict[str, dict[tuple, int]] = {}
for model, _ in top5:
    model_em_map[model] = {}

for r in records:
    m = r["model_name"]
    if m not in model_em_map:
        continue
    key = (r["conflict_id"], r["file_path"])
    model_em_map[m][key] = 1 if r["exact_match"] else 0


def mcnemar_test(vec_a, vec_b):
    """
    McNemar's exact / chi-squared test.
    b = A correct, B wrong; c = A wrong, B correct.
    Uses mid-p correction (chi2 with continuity correction for large b+c).
    Returns p-value.
    """
    b = sum(1 for a, bv in zip(vec_a, vec_b) if a == 1 and bv == 0)
    c = sum(1 for a, bv in zip(vec_a, vec_b) if a == 0 and bv == 1)
    if b + c == 0:
        return b, c, 1.0  # no discordant pairs
    # Chi-squared with continuity correction
    chi2_stat = (abs(b - c) - 1) ** 2 / (b + c)
    p = 1 - chi2.cdf(chi2_stat, df=1)
    return b, c, p


mcnemar_rows = []
for i in range(len(top5)):
    for j in range(i + 1, len(top5)):
        model_a, da = top5[i]
        model_b, db = top5[j]
        # Find shared keys
        keys_a = set(model_em_map[model_a].keys())
        keys_b = set(model_em_map[model_b].keys())
        shared = sorted(keys_a & keys_b)
        if len(shared) == 0:
            continue
        vec_a = [model_em_map[model_a][k] for k in shared]
        vec_b = [model_em_map[model_b][k] for k in shared]
        b, c, p = mcnemar_test(vec_a, vec_b)
        sig = "***" if p < 0.001 else ("**" if p < 0.01 else ("*" if p < 0.05 else "ns"))
        print(f"{model_a:<35} {model_b:<35} {b:>5} {c:>5} {p:>12.4f} {sig:>6}")
        mcnemar_rows.append((model_a, model_b, b, c, p, sig))

# ---------------------------------------------------------------------------
# 6. Summary of top-10 models (for paper)
# ---------------------------------------------------------------------------
print("\n% ---- Top-10 model summary ----")
for rank, (model, d) in enumerate(sorted_models[:10], 1):
    print(
        f"  {rank:2d}. {model:<40} EM={d['em']:.1f}% "
        f"95%CI=[{d['ci_lo']:.1f}, {d['ci_hi']:.1f}] N={d['n']}"
    )
